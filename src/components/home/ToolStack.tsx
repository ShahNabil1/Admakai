import { motion } from 'framer-motion';
import { Clapperboard, Camera, AudioLines, Scissors } from 'lucide-react';
import { useMotionPreference } from '@/hooks/use-motion-preference';
import { Reveal } from '@/components/motion/Reveal';
import { toolCards, toolSprites, type Tool } from '@/data/tools';
import './tool-stack.css';

const ease = [0.22, 1, 0.36, 1] as const;
const icons = { video: Clapperboard, image: Camera, voice: AudioLines, edit: Scissors };

const SPRITE = '/tools/tools-sprite.png';
const SPRITE_SCALE = 3.2; // one 64px sheet cell becomes a 20px icon

export function ToolIcon({ tool }: { tool: Tool }) {
  const pos = toolSprites[tool.slug];
  if (pos) {
    return (
      <span
        className="ts-badge__icon"
        aria-hidden="true"
        style={{
          backgroundImage: `url(${SPRITE})`,
          backgroundSize: '80px 60px',
          backgroundPosition: `${-pos[0] / SPRITE_SCALE}px ${-pos[1] / SPRITE_SCALE}px`,
          backgroundRepeat: 'no-repeat',
        }}
      />
    );
  }
  return (
    <span className="ts-badge__icon ts-badge__mono" style={{ background: tool.color, color: tool.dark ? '#111' : '#fff' }} aria-hidden="true">
      {tool.name[0]}
    </span>
  );
}

function Sparkle() {
  return (
    <svg className="ts-sparkle" width="28" height="28" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
      <path d="M12 0c.6 6.2 5.8 11.4 12 12-6.2.6-11.4 5.8-12 12-.6-6.2-5.8-11.4-12-12C6.2 11.4 11.4 6.2 12 0z" />
    </svg>
  );
}

export function ToolStack() {
  const reduce = useMotionPreference();
  const view = { once: true, margin: '-80px' } as const;
  return (
    <section className="ts" aria-labelledby="ts-title">
      <div className="ts__inner">
        <div className="ts__head">
          <Reveal>
            <span className="ts__pill">
              <svg width="14" height="14" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M13 2 4 14h7l-1 8 9-12h-7l1-8z" /></svg>
              Our stack
            </span>
          </Reveal>
          <Reveal delay={0.1}>
            <h2 id="ts-title" className="ts__title">
              <span className="font-display">Human taste</span> <Sparkle /> <span>at AI speed</span>
            </h2>
          </Reveal>
          <Reveal delay={0.2}>
            <p className="ts__sub">We use AI to produce more, and to produce better. Every Admakai ad is generated by the strongest models available right now and finished by a human director and editor, so the result looks like a shoot, at the speed of a render.</p>
          </Reveal>
        </div>
        <div className="ts__grid">
          {toolCards.map((c, i) => {
            const Icon = icons[c.icon];
            return (
              <motion.article
                key={c.icon}
                className="ts-card"
                initial={reduce ? false : { opacity: 0, y: 40 }}
                whileInView={{ opacity: 1, y: 0 }}
                viewport={view}
                transition={{ delay: reduce ? 0 : i * 0.1, duration: reduce ? 0 : 0.7, ease }}
              >
                <span className="ts-card__tile" style={{ background: c.tile }}><Icon size={20} strokeWidth={1.75} color="#fff" /></span>
                <h3 className="ts-card__title">
                  {c.title.map((p) => <span key={p.text} className={p.serif ? 'font-display' : undefined}>{p.text}</span>)}
                </h3>
                <p className="ts-card__text">{c.text}</p>
                <hr className="ts-card__rule" />
                <p className="ts-card__label font-display">Tasks</p>
                <p className="ts-card__text">{c.tasks}</p>
                <hr className="ts-card__rule" />
                <ul className="ts-card__badges">
                  {c.tools.map((tool, j) => (
                    <motion.li
                      key={tool.slug}
                      className="ts-badge"
                      initial={reduce ? false : { opacity: 0, scale: 0.8 }}
                      whileInView={{ opacity: 1, scale: 1 }}
                      viewport={view}
                      transition={{ delay: reduce ? 0 : i * 0.1 + 0.7 + j * 0.05, duration: reduce ? 0 : 0.35, ease }}
                    >
                      <ToolIcon tool={tool} />
                      <span className="ts-badge__name">{tool.name}</span>
                    </motion.li>
                  ))}
                </ul>
              </motion.article>
            );
          })}
        </div>
        <p className="sr-only">Admakai builds AI ads with Seedance, Veo, Kling, Seedream, Midjourney, ElevenLabs and Claude, directed and edited by humans.</p>
      </div>
    </section>
  );
}
